/// First-run / edit profiler session.
#[derive(Debug, Clone)]
pub struct ProfilerSession<'a> {
    pub non_interactive: bool,
    pub home: &'a Path,
    pub platform: Platform,
    pub existing: Option<&'a Profile>,
}

pub fn discover_defaults(home: &Path, platform: Platform) -> Result<Profile> {
    run_profiler(&ProfilerSession {
        non_interactive: true,
        home,
        platform,
        existing: None,
    })
}

/// Build a profile from the home scan + catalog, without prompting.
pub fn build_profile(session: &ProfilerSession<'_>) -> Result<Profile> {
    let hits = scan_home(session.home)?;
    let mut components = Vec::new();
    let mut used_ids = BTreeSet::new();
    let mut used_paths = BTreeSet::new();

    let catalog_paths: Vec<String> = CATALOG
        .iter()
        .filter_map(|e| match session.platform {
            Platform::Linux => e.linux,
            Platform::MacOs => e.macos,
        })
        .map(str::to_string)
        .collect();

    for entry in CATALOG {
        let mut component = catalog_component(entry);
        if let Some(logical) = component.path_for(session.platform).map(str::to_string) {
            let abs = expand_tilde(&logical, session.home);
            component.include = abs.exists();
            used_paths.insert(logical);
        }
        used_ids.insert(component.id.clone());
        components.push(component);
    }

    for hit in hits {
        merge_scan_hit(
            session,
            hit,
            &catalog_paths,
            &mut components,
            &mut used_ids,
            &mut used_paths,
        );
    }

    if let Some(existing) = session.existing {
        overlay_existing(session.platform, existing, &mut components, &mut used_ids);
    }

    Ok(Profile {
        schema_version: 1,
        components,
        secret_references: session
            .existing
            .map(|p| p.secret_references.clone())
            .unwrap_or_default(),
        notes: Some(
            "Generated by cyclone init from a scan of ~/.config and ~/. \
SSH private keys, keychains, browser data, and large caches stay excluded unless you opt in. \
Edit this file or re-run `cyclone profile --edit`."
                .into(),
        ),
    })
}

pub fn run_profiler(session: &ProfilerSession<'_>) -> Result<Profile> {
    let mut profile = build_profile(session)?;

    if session.non_interactive || !io::stdout().is_terminal() {
        return Ok(profile);
    }

    print_session_header(session)?;
    print_candidate_groups(&profile, session)?;
    writeln!(
        io::stdout(),
        "SSH private keys, keychains, browser data, and large caches are listed as opt-in only."
    )?;

    write!(
        io::stdout(),
        "Add from this scan: ids or paths to toggle/include (space or comma separated),\n\
         extra paths to add, or press Enter to keep the selection: "
    )?;
    io::stdout().flush()?;
    let mut extra = String::new();
    io::stdin().read_line(&mut extra)?;
    let extra = extra.trim();
    if !extra.is_empty() {
        let warnings = apply_selection_line(&mut profile, extra, session.home)?;
        for w in warnings {
            writeln!(io::stdout(), "note: {w}")?;
        }
    }

    write!(
        io::stdout(),
        "Track a secret by reference name (or Enter to skip): "
    )?;
    io::stdout().flush()?;
    let mut secret_name = String::new();
    io::stdin().read_line(&mut secret_name)?;
    let secret_name = secret_name.trim();
    if !secret_name.is_empty()
        && !profile
            .secret_references
            .iter()
            .any(|s| s.name == secret_name)
    {
        profile.secret_references.push(SecretReference {
            name: secret_name.to_string(),
            provider: "prompt".into(),
            path_hint: None,
        });
    }

    Ok(profile)
}

/// Toggle catalog/scan ids, or add/include extra paths from a user line.
pub fn apply_selection_line(profile: &mut Profile, line: &str, home: &Path) -> Result<Vec<String>> {
    let mut warnings = Vec::new();
    let tokens = line
        .split(|c: char| c.is_whitespace() || c == ',')
        .filter(|t| !t.is_empty());
    for token in tokens {
        if let Some(c) = profile.components.iter_mut().find(|c| c.id == token) {
            c.include = !c.include;
            continue;
        }
        if looks_like_path(token) {
            include_or_add_path(profile, token, home)?;
            continue;
        }
        warnings.push(format!(
            "unknown component id `{token}` (use a listed id or a path such as ~/.inputrc)"
        ));
    }
    profile.validate()?;
    Ok(warnings)
}

fn looks_like_path(token: &str) -> bool {
    token.starts_with('~')
        || token.starts_with('.')
        || token.starts_with('/')
        || token.contains('/')
}

fn include_or_add_path(profile: &mut Profile, raw: &str, home: &Path) -> Result<()> {
    let abs = expand_tilde(raw, home);
    let logical = if abs.starts_with(home) {
        to_logical(&abs, home)
    } else {
        raw.to_string()
    };
    if let Some(c) = profile.components.iter_mut().find(|c| {
        c.linux.as_deref() == Some(logical.as_str()) || c.macos.as_deref() == Some(logical.as_str())
    }) {
        c.include = true;
        return Ok(());
    }
    if !abs.exists() {
        return Err(CycloneError::User(format!(
            "path `{raw}` does not exist under {}",
            home.display()
        )));
    }
    let kind = if abs.is_dir() {
        ComponentKind::ConfigTree
    } else {
        ComponentKind::Dotfile
    };
    let used: BTreeSet<String> = profile.components.iter().map(|c| c.id.clone()).collect();
    let id = component_id_for(&logical, &used);
    let opt_in = crate::scan::classify(&logical);
    profile.components.push(ProfileComponent {
        id,
        kind,
        include: true,
        linux: Some(logical.clone()),
        macos: Some(logical),
        supported_platforms: vec![Platform::Linux, Platform::MacOs],
        opt_in,
    });
    Ok(())
}

fn catalog_component(entry: &CatalogEntry) -> ProfileComponent {
    ProfileComponent {
        id: entry.id.to_string(),
        kind: entry.kind,
        include: false,
        linux: entry.linux.map(str::to_string),
        macos: entry.macos.map(str::to_string),
        supported_platforms: entry.platforms.to_vec(),
        opt_in: None,
    }
}

fn merge_scan_hit(
    session: &ProfilerSession<'_>,
    hit: ScanHit,
    catalog_paths: &[String],
    components: &mut Vec<ProfileComponent>,
    used_ids: &mut BTreeSet<String>,
    used_paths: &mut BTreeSet<String>,
) {
    if let Some(existing) = components
        .iter_mut()
        .find(|c| c.path_for(session.platform) == Some(hit.logical.as_str()))
    {
        if existing.opt_in.is_none() {
            existing.opt_in = hit.opt_in;
        }
        if hit.opt_in.is_some() {
            existing.include = false;
        }
        used_paths.insert(hit.logical);
        return;
    }

    let ancestor_of_catalog = catalog_paths
        .iter()
        .any(|cp| logical_is_prefix(&hit.logical, cp));
    let include = hit.opt_in.is_none() && !ancestor_of_catalog;
    let id = component_id_for(&hit.logical, used_ids);
    used_ids.insert(id.clone());
    used_paths.insert(hit.logical.clone());
    components.push(ProfileComponent {
        id,
        kind: hit.kind,
        include,
        linux: Some(hit.logical.clone()),
        macos: Some(hit.logical),
        supported_platforms: vec![Platform::Linux, Platform::MacOs],
        opt_in: hit.opt_in,
    });
}

fn overlay_existing(
    platform: Platform,
    existing: &Profile,
    components: &mut Vec<ProfileComponent>,
    used_ids: &mut BTreeSet<String>,
) {
    for extra in &existing.components {
        if let Some(c) = components.iter_mut().find(|c| c.id == extra.id) {
            c.include = extra.include;
            continue;
        }
        if let Some(path) = extra.path_for(platform) {
            if let Some(c) = components
                .iter_mut()
                .find(|c| c.path_for(platform) == Some(path))
            {
                c.include = extra.include;
                continue;
            }
        }
        used_ids.insert(extra.id.clone());
        components.push(extra.clone());
    }
}

fn print_session_header(session: &ProfilerSession<'_>) -> Result<()> {
    writeln!(io::stdout(), "Cyclone setup profiler")?;
    writeln!(
        io::stdout(),
        "Home: {} ({})",
        session.home.display(),
        session.platform
    )?;
    writeln!(
        io::stdout(),
        "Scanning ~/.config and ~/ for dotfiles and config-like files:"
    )?;
    Ok(())
}

fn print_candidate_groups(profile: &Profile, session: &ProfilerSession<'_>) -> Result<()> {
    let mut included = Vec::new();
    let mut addable = Vec::new();
    let mut opt_in = Vec::new();
    let mut missing = Vec::new();

    for c in &profile.components {
        let found = component_found(c, session);
        match (c.include, found, c.opt_in) {
            (true, _, _) => included.push(c),
            (false, true, Some(_)) => opt_in.push(c),
            (false, true, None) => addable.push(c),
            (false, false, _) => missing.push(c),
        }
    }

    if !included.is_empty() {
        writeln!(io::stdout(), "\nSuggested (will be captured):")?;
        for c in included {
            write_row(c, session, None)?;
        }
    }
    if !addable.is_empty() {
        writeln!(io::stdout(), "\nAlso found — type an id or path to add:")?;
        for c in addable {
            write_row(c, session, None)?;
        }
    }
    if !opt_in.is_empty() {
        writeln!(io::stdout(), "\nOpt-in (excluded unless you add them):")?;
        for c in opt_in {
            write_row(c, session, c.opt_in)?;
        }
    }
    if !missing.is_empty() {
        writeln!(io::stdout(), "\nWell-known paths not on this machine:")?;
        for c in missing {
            write_row(c, session, None)?;
        }
    }
    writeln!(io::stdout())?;
    Ok(())
}

fn component_found(c: &ProfileComponent, session: &ProfilerSession<'_>) -> bool {
    c.path_for(session.platform)
        .map(|p| expand_tilde(p, session.home).exists())
        .unwrap_or(false)
}

fn write_row(
    c: &ProfileComponent,
    session: &ProfilerSession<'_>,
    reason: Option<OptInReason>,
) -> Result<()> {
    let logical = c
        .path_for(session.platform)
        .unwrap_or("(no path on this OS)");
    let found = component_found(c, session);
    let mark = if c.include { "x" } else { " " };
    let extra = if let Some(r) = reason {
        r.as_str().to_string()
    } else if !found {
        "missing".to_string()
    } else {
        String::new()
    };
    writeln!(
        io::stdout(),
        "  [{mark}] {:<22} {:<48} {extra}",
        c.id,
        logical
    )?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::scan::write_fixture_tree;
    use tempfile::tempdir;

    fn included_ids(profile: &Profile) -> Vec<&str> {
        profile
            .included()
            .map(|c| c.id.as_str())
            .collect::<Vec<_>>()
    }

    fn by_path<'a>(profile: &'a Profile, logical: &str) -> &'a ProfileComponent {
        profile
            .components
            .iter()
            .find(|c| c.linux.as_deref() == Some(logical) || c.macos.as_deref() == Some(logical))
            .unwrap_or_else(|| panic!("missing {logical}"))
    }

    #[test]
    fn discovers_existing_dotfiles_only() {
        let dir = tempdir().unwrap();
        std::fs::write(dir.path().join(".gitconfig"), "[user]\n").unwrap();
        let profile = discover_defaults(dir.path(), Platform::Linux).unwrap();
        let git = profile
            .components
            .iter()
            .find(|c| c.id == "gitconfig")
            .unwrap();
        assert!(git.include);
        let nvim = profile.components.iter().find(|c| c.id == "nvim").unwrap();
        assert!(!nvim.include);
        assert!(profile.components.iter().all(|c| c.id != "ssh"));
        assert!(profile
            .components
            .iter()
            .all(|c| c.opt_in != Some(OptInReason::SshPrivateKey) || !c.include));
    }

    #[test]
    fn scan_adds_non_catalog_dotfiles_and_keeps_exclusions_opt_in() {
        let dir = tempdir().unwrap();
        write_fixture_tree(dir.path()).unwrap();
        let profile = discover_defaults(dir.path(), Platform::Linux).unwrap();

        assert!(by_path(&profile, "~/.tmux.conf").include);
        assert!(by_path(&profile, "~/.config/htop").include);
        assert!(by_path(&profile, "~/.gitconfig").include);
        assert!(by_path(&profile, "~/.config/nvim").include);
        assert!(by_path(&profile, "~/.ssh/config").include);
        assert!(by_path(&profile, "~/.ssh/id_ed25519.pub").include);

        let key = by_path(&profile, "~/.ssh/id_ed25519");
        assert!(!key.include);
        assert_eq!(key.opt_in, Some(OptInReason::SshPrivateKey));

        let chrome = by_path(&profile, "~/.config/google-chrome");
        assert!(!chrome.include);
        assert_eq!(chrome.opt_in, Some(OptInReason::BrowserData));

        let cache = by_path(&profile, "~/.cache");
        assert!(!cache.include);
        assert_eq!(cache.opt_in, Some(OptInReason::LargeCache));

        let gnupg = by_path(&profile, "~/.gnupg");
        assert!(!gnupg.include);
        assert_eq!(gnupg.opt_in, Some(OptInReason::Keychain));

        // More specific catalog path wins; the parent tree is still listed.
        let apt_dir = by_path(&profile, "~/.config/apt");
        assert!(!apt_dir.include);
        assert!(by_path(&profile, "~/.config/apt/packages.list").include);

        assert!(profile
            .components
            .iter()
            .all(|c| c.linux.as_deref() != Some("~/Documents/notes.txt")));
        assert!(!included_ids(&profile).is_empty());
    }

    #[test]
    fn selection_line_opts_in_scanned_exclusion_and_toggles_ids() {
        let dir = tempdir().unwrap();
        write_fixture_tree(dir.path()).unwrap();
        let mut profile = discover_defaults(dir.path(), Platform::Linux).unwrap();
        assert!(!by_path(&profile, "~/.ssh/id_ed25519").include);
        assert!(by_path(&profile, "~/.tmux.conf").include);

        let warnings =
            apply_selection_line(&mut profile, "tmux-conf ~/.ssh/id_ed25519", dir.path()).unwrap();
        assert!(warnings.is_empty());
        assert!(!by_path(&profile, "~/.tmux.conf").include);
        assert!(by_path(&profile, "~/.ssh/id_ed25519").include);
    }

    #[test]
    fn existing_profile_keeps_opt_in_include() {
        let dir = tempdir().unwrap();
        write_fixture_tree(dir.path()).unwrap();
        let mut existing = discover_defaults(dir.path(), Platform::Linux).unwrap();
        by_path_mut(&mut existing, "~/.ssh/id_ed25519").include = true;
        let session = ProfilerSession {
            non_interactive: true,
            home: dir.path(),
            platform: Platform::Linux,
            existing: Some(&existing),
        };
        let profile = build_profile(&session).unwrap();
        assert!(by_path(&profile, "~/.ssh/id_ed25519").include);
    }

    fn by_path_mut<'a>(profile: &'a mut Profile, logical: &str) -> &'a mut ProfileComponent {
        profile
            .components
            .iter_mut()
            .find(|c| c.linux.as_deref() == Some(logical) || c.macos.as_deref() == Some(logical))
            .unwrap_or_else(|| panic!("missing {logical}"))
    }
}
