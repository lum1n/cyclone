use std::io::{self, IsTerminal, Write};
use std::path::PathBuf;

use crate::error::Result;
use crate::manifest::SecretReference;
use crate::platform::Platform;
use crate::profile::{Profile, ToolDeclaration};

/// Interactive first-run profiler (stub: reads stdin; non-interactive env uses defaults).
#[derive(Debug, Default)]
pub struct ProfilerSession {
    pub non_interactive: bool,
}

pub fn discover_defaults() -> Result<Profile> {
    let home = directories::UserDirs::new()
        .map(|u| u.home_dir().to_path_buf())
        .unwrap_or_else(|| PathBuf::from("."));

    let mut roots = vec![home.join(".config/nvim"), home.join(".gitconfig")];
    roots.retain(|p| p.exists());

    Ok(Profile {
        schema_version: 1,
        capture_roots: roots,
        tool_declarations: vec![
            ToolDeclaration {
                name: "git".into(),
                kind: "system".into(),
                pin: None,
                supported_platforms: vec![Platform::Linux, Platform::MacOs],
            },
            ToolDeclaration {
                name: "rustc".into(),
                kind: "rustup".into(),
                pin: None,
                supported_platforms: vec![Platform::Linux, Platform::MacOs],
            },
        ],
        secret_references: Vec::new(),
        notes: Some("Generated by cyclone profile (stub)".into()),
    })
}

pub fn run_interactive_profiler(session: &ProfilerSession) -> Result<Profile> {
    if session.non_interactive || !io::stdout().is_terminal() {
        return discover_defaults();
    }

    let mut profile = discover_defaults()?;

    writeln!(io::stdout(), "Cyclone setup profiler (stub)")?;
    writeln!(
        io::stdout(),
        "Suggested capture roots: {:?}",
        profile.capture_roots
    )?;
    write!(io::stdout(), "Add another path (or press Enter to skip): ")?;
    io::stdout().flush()?;
    let mut extra = String::new();
    io::stdin().read_line(&mut extra)?;
    let extra = extra.trim();
    if !extra.is_empty() {
        profile.capture_roots.push(PathBuf::from(extra));
    }

    write!(
        io::stdout(),
        "Track a secret by reference name (or Enter to skip): "
    )?;
    io::stdout().flush()?;
    let mut secret_name = String::new();
    io::stdin().read_line(&mut secret_name)?;
    let secret_name = secret_name.trim();
    if !secret_name.is_empty() {
        profile.secret_references.push(SecretReference {
            name: secret_name.to_string(),
            provider: "prompt".into(),
            path_hint: None,
        });
    }

    Ok(profile)
}
